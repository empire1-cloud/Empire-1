def build_signal_to_sequence(signal: dict, persona: dict, offer: dict, context: dict) -> dict:
    signal_name = signal.get("signal_name", "General signal")
    persona_type = persona.get("type", "general")
    offer_name = offer.get("name", "Revenue System")
    channel = persona.get("best_channel", "email")

    sequence_type = signal.get("sequence_type", "automated_nurture")

    sequences = {
        "personalized": [
            {"day": 1, "action": f"Send personalized DM via {channel}", "template": f"Hey {{name}}, I noticed {{signal_angle}}. We generated a revenue system for {offer_name} — want to see it?", "channel": channel},
            {"day": 3, "action": "Follow up with value add", "template": f"Hey {{name}}, following up on the {offer_name} system. Quick wins: {{quick_win}}. Worth 5 min?", "channel": channel},
            {"day": 7, "action": "Call or close attempt", "template": f"Last follow-up on the {offer_name} system. If timing is off, no worries — the offer is ready when you are.", "channel": channel},
        ],
        "signal_triggered": [
            {"day": 1, "action": f"Signal-triggered outreach via {channel}", "template": f"Hey {{name}}, saw {{signal_angle}}. We built a revenue system for {offer_name}. Want the breakdown?", "channel": channel},
            {"day": 4, "action": "Follow up with social proof", "template": f"Hey {{name}}, we've helped {{similar_count}} similar businesses with {offer_name}. Quick case study available.", "channel": channel},
            {"day": 8, "action": "Final touch", "template": f"Last note on the {offer_name} system. Happy to share results from similar {{segment}} businesses.", "channel": channel},
        ],
        "automated_nurture": [
            {"day": 1, "action": f"Automated email sequence start", "template": f"Subject: Revenue system for {{business}}\n\nHi {{name}},\n\nWe built a revenue system for {offer_name}. Here's what's inside:\n→ 3 paid offers\n→ 25 buyer profiles\n→ Outreach campaign\n→ Payment path\n→ Delivery receipt", "channel": "email"},
            {"day": 4, "action": "Value email with offer details", "template": f"Subject: How {{segment}} businesses are using {offer_name}\n\nHi {{name}},\n\nMost {{segment}} businesses we work with see first results within 72 hours. Here's the playbook: [link]", "channel": "email"},
            {"day": 10, "action": "Soft close", "template": f"Subject: Ready when you are\n\nHi {{name}},\n\nThe {offer_name} system is ready. If now is not the right time, I'll check back next month.", "channel": "email"},
        ],
        "monitor": [
            {"day": 1, "action": "Add to watch list", "template": f"Tracking {{name}} for re-scoring opportunities.", "channel": "none"},
            {"day": 7, "action": "Re-score", "template": "Weekly re-score check.", "channel": "none"},
        ],
    }

    sequence = sequences.get(sequence_type, sequences["automated_nurture"])

    return {
        "signal_name": signal_name,
        "persona_type": persona_type,
        "offer_name": offer_name,
        "sequence_type": sequence_type,
        "steps": sequence,
        "total_steps": len(sequence),
        "channel": channel,
        "urgency": signal.get("priority", 50),
    }


