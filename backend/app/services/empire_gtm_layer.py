def detect_signals(input_data: dict, context: dict) -> dict:
    signals_lib = context.get("signals", {}).get("signals", [])
    business_name = input_data.get("business_name", "")
    business_type = input_data.get("business_type", "other")
    offer = input_data.get("current_offer", "")
    target = input_data.get("target_customer", "")
    constraints = input_data.get("constraints", "")
    notes = input_data.get("links_or_notes", "")
    channel = input_data.get("preferred_sales_channel", "mixed")

    combined = f"{business_name} {offer} {target} {constraints} {notes}".lower()

    matched_signals = []
    for sig in signals_lib:
        persona_types = [p.lower() for p in sig.get("persona_types", [])]
        if business_type.lower() in " ".join(persona_types):
            matched_signals.append(sig)
            continue
        if target.lower() in " ".join(persona_types):
            matched_signals.append(sig)
            continue
        keywords = sig.get("name", "").lower().split()
        if any(k in combined for k in keywords):
            matched_signals.append(sig)

    matched_signals = matched_signals[:5]

    return {
        "business_name": business_name,
        "detected_signals": [
            {
                "signal_id": s.get("id"),
                "signal_name": s.get("name"),
                "priority": s.get("priority"),
                "sequence_type": s.get("sequence_type"),
                "outreach_angle": s.get("outreach_angle", ""),
            }
            for s in matched_signals
        ],
        "signal_count": len(matched_signals),
        "best_channel": channel,
        "summary": f"Detected {len(matched_signals)} signal(s) for {business_name}" if matched_signals else f"No strong signals detected for {business_name}",
    }


