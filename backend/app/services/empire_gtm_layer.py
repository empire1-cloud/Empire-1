def load_gtm_context() -> dict:
    return {
        "profile": _load("profile"),
        "icp": _load("icp_definition"),
        "signals": _load("signal_library"),
        "positioning": _load("positioning"),
        "competitors": _load("competitor_radar"),
        "personas": _load("personas"),
        "campaigns": _load_list("campaigns"),
        "scoring_outputs": _load_list("scoring_outputs"),
        "weekly_updates": _load_list("weekly_updates"),
    }


def save_gtm_context(context: dict):
    for key in ("profile", "icp", "signals", "positioning", "competitors", "personas"):
        if key in context:
            _save(key, context[key])
    if "campaigns" in context:
        _save_list("campaigns", context["campaigns"])
    if "scoring_outputs" in context:
        _save_list("scoring_outputs", context["scoring_outputs"])
    if "weekly_updates" in context:
        _save_list("weekly_updates", context["weekly_updates"])


