# CAMPAIGN PLAN
# ---------------------------------------------------------

def generate_campaign_plan(revenue_os_output: dict, context: dict, request_data: Optional[dict] = None) -> dict:
    rd = revenue_os_output.get("receipt", {}).get("revenue_diagnosis", {})
    biz = rd.get("business_name", request_data.get("business_name", "Unknown") if request_data else "Unknown")
    offer_name = rd.get("current_offer", "Revenue System")
    buyers = revenue_os_output.get("buyer_profiles", [])
    offers = revenue_os_output.get("forged_offers", [])
    outreach = revenue_os_output.get("outreach_campaign", {})

    scored_buyers = [score_buyer_profile(b, context) for b in buyers]

    tier1 = [b for b in scored_buyers if b["tier"] == "Tier 1"]
    tier2 = [b for b in scored_buyers if b["tier"] == "Tier 2"]
    tier3 = [b for b in scored_buyers if b["tier"] == "Tier 3"]

    signals = context.get("signals", {}).get("signals", [])
    personas = context.get("personas", {}).get("personas", [])

    campaign_id = f"CAM-{uuid.uuid4().hex[:8].upper()}"

    sequence_plan = []
    for buyer in tier1[:3]:
        persona = next((p for p in personas if p["type"] in buyer["persona_type"].lower()), {"type": "general", "best_channel": "email"})
        sig = next(iter(buyer.get("detected_signals", [])), {"signal_name": "High ICP fit", "sequence_type": "personalized", "priority": 85})
        offer = next(iter(offers), {"name": offer_name})
        seq = build_signal_to_sequence(sig, persona, offer, context)
        sequence_plan.append(seq)

    if not sequence_plan and tier2:
        for buyer in tier2[:2]:
            persona = {"type": buyer["persona_type"], "best_channel": "email"}
            sig = {"signal_name": "Signal-triggered opportunity", "sequence_type": "signal_triggered", "priority": 70}
            offer = {"name": offer_name}
            seq = build_signal_to_sequence(sig, persona, offer, context)
            sequence_plan.append(seq)

    if not sequence_plan:
        persona = {"type": "general", "best_channel": "email"}
        sig = {"signal_name": "General opportunity", "sequence_type": "automated_nurture", "priority": 50}
        offer = {"name": offer_name}
        sequence_plan.append(build_signal_to_sequence(sig, persona, offer, context))

    campaign = {
        "id": campaign_id,
        "business_name": biz,
        "offer_name": offer_name,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "status": "draft",
        "buyer_breakdown": {
            "tier_1_count": len(tier1),
            "tier_2_count": len(tier2),
            "tier_3_count": len(tier3),
            "total_scored": len(scored_buyers),
        },
        "top_tier_buyers": scored_buyers[:5],
        "sequence_plan": sequence_plan,
        "recommended_channel": tier1[0]["best_channel"] if tier1 else "email",
        "total_sequence_steps": sum(len(s["steps"]) for s in sequence_plan),
    }

    campaigns = _load_list("campaigns")
    campaigns.append(campaign)
    _save_list("campaigns", campaigns)

    return campaign


