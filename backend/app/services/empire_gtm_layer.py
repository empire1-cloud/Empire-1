def score_buyer_profile(profile: dict, context: dict) -> dict:
    icp = context.get("icp", {})
    segments = icp.get("icp_segments", [])
    signals = context.get("signals", {}).get("signals", [])

    segment = profile.get("segment", "")
    persona_type = profile.get("persona_type", "")
    priority_score = profile.get("priority_score", 50)

    icp_fit = 0
    matched_segment = None
    for seg in segments:
        if seg["segment"].lower() in segment.lower() or seg["segment"].lower() in persona_type.lower():
            icp_fit = seg.get("fit_score", 50)
            matched_segment = seg
            break
    if not icp_fit and segment:
        for seg in segments:
            if any(s.lower() in segment.lower() for s in seg.get("signals", [])):
                icp_fit = seg.get("fit_score", 30) - 10
                matched_segment = seg
                break
    if not icp_fit:
        icp_fit = 30

    signal_score = 0
    detected_signals = []
    for sig in signals:
        sig_personas = [p.lower() for p in sig.get("persona_types", [])]
        if persona_type.lower() in sig_personas or segment.lower() in sig_personas:
            detected_signals.append({
                "signal_id": sig.get("id"),
                "signal_name": sig.get("name"),
                "priority": sig.get("priority"),
                "sequence_type": sig.get("sequence_type"),
                "outreach_angle": sig.get("outreach_angle"),
            })
            signal_score = max(signal_score, sig.get("priority", 0))

    if not detected_signals:
        signal_score = max(0, priority_score - 20)

    total_score = min(100, icp_fit + signal_score)

    tier = _assign_tier(total_score)

    return {
        "persona_type": persona_type,
        "segment": segment,
        "icp_fit": icp_fit,
        "signal_score": signal_score,
        "total_score": total_score,
        "tier": tier,
        "detected_signals": detected_signals[:3],
        "best_channel": profile.get("best_channel", matched_segment.get("best_channels", ["email"])[0] if matched_segment else "email"),
        "recommended_action": _action_for_tier(tier, profile),
        "recommended_sequence_type": detected_signals[0]["sequence_type"] if detected_signals else "automated_nurture" if tier in ("Tier 3", "Monitor") else "personalized",
    }


def score_account(account: dict, context: dict) -> dict:
    icp = context.get("icp", {})
    segments = icp.get("icp_segments", [])
    signals_lib = context.get("signals", {}).get("signals", [])

    name = account.get("name", "Unknown")
    segment = account.get("segment", "")
    signals_raw = account.get("signals", [])

    icp_fit = 0
    for seg in segments:
        if seg["segment"].lower() in segment.lower():
            icp_fit = seg.get("fit_score", 50)
            break
    if not icp_fit:
        icp_fit = 30

    urgency = account.get("urgency", "normal")
    urgency_map = {"critical": 20, "high": 15, "normal": 10, "low": 5}
    urgency_score = urgency_map.get(urgency, 10)

    budget = account.get("budget", 0)
    budget_score = min(15, budget / 100) if budget else 0

    signal_score = 0
    detected = []
    for s in signals_raw:
        for lib_sig in signals_lib:
            if lib_sig.get("name", "").lower() in s.lower():
                detected.append(lib_sig)
                signal_score = max(signal_score, lib_sig.get("priority", 0))
    if not detected and signals_raw:
        signal_score = 20

    total_score = min(100, icp_fit + urgency_score + budget_score + signal_score)
    tier = _assign_tier(total_score)

    return {
        "name": name,
        "segment": segment,
        "icp_fit": icp_fit,
        "urgency_score": urgency_score,
        "budget_score": budget_score,
        "signal_score": signal_score,
        "total_score": total_score,
        "tier": tier,
        "detected_signals": [{"signal_id": s.get("id"), "signal_name": s.get("name")} for s in detected[:3]],
        "recommended_action": _action_for_tier(tier, account),
    }


def _assign_tier(score: int) -> str:
    if score >= 80:
        return "Tier 1"
    if score >= 60:
        return "Tier 2"
    if score >= 40:
        return "Tier 3"
    if score >= 20:
        return "Monitor"
    return "Exclude"


def _action_for_tier(tier: str, profile: dict) -> str:
    actions = {
        "Tier 1": "Immediate personalized outreach within 24 hours",
        "Tier 2": "Signal-triggered sequence within 48 hours",
        "Tier 3": "Automated nurture sequence",
        "Monitor": "Track and re-score weekly",
        "Exclude": "No outreach — does not fit ICP",
    }
    return actions.get(tier, "No action")


