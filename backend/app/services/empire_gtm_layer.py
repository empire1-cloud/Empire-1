# WEEKLY GTM UPDATE
# ---------------------------------------------------------

def generate_weekly_gtm_update(context: dict, recent_commands: list, recent_leads: list) -> dict:
    icp = context.get("icp", {})
    segments = icp.get("icp_segments", [])

    total_commands = len(recent_commands)
    total_leads = len(recent_leads)
    paid_leads = sum(1 for l in recent_leads if l.get("status") == "paid")
    pipeline_value = sum(l.get("estimated_value", 0) or 0 for l in recent_leads)
    paid_value = sum(l.get("actual_value", 0) or 0 for l in recent_leads)

    top_segment = max(segments, key=lambda s: s.get("fit_score", 0)) if segments else {}
    commands_this_week = recent_commands[-10:] if len(recent_commands) > 10 else recent_commands

    update_id = f"WEEKLY-{uuid.uuid4().hex[:8].upper()}"

    update = {
        "id": update_id,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "period": "This week",
        "metrics": {
            "commands_run": total_commands,
            "leads_created": total_leads,
            "paid_leads": paid_leads,
            "pipeline_value": pipeline_value,
            "actual_revenue": paid_value,
        },
        "top_icp_segment": top_segment.get("segment", "General"),
        "top_icp_score": top_segment.get("fit_score", 0),
        "recommended_focus": f"Focus on {top_segment.get('segment', 'top')} segment — highest ICP fit",
        "recommended_action_items": [
            f"Run {max(5, 10 - total_commands)} more revenue commands this week",
            f"Target {max(10, 20 - total_leads)} new leads in the {top_segment.get('segment', 'top')} segment",
            "Review and re-score existing leads",
            "Send weekly outreach to monitor-tier leads",
            "Generate delivery receipts for paid leads",
        ],
        "commands_this_week": [{"id": c.get("id"), "business": c.get("business_name"), "created_at": c.get("created_at")} for c in commands_this_week],
        "next_update_cadence": "Every Monday",
    }

    updates = _load_list("weekly_updates")
    updates.append(update)
    _save_list("weekly_updates", updates)

    return update


# ---------------------------------------------------------
# ATTACH TO REVENUE OS
# ---------------------------------------------------------

def attach_gtm_to_revenue_os(revenue_os_output: dict, request_data: dict, context: dict) -> dict:
    gtm_signals = detect_signals(request_data, context)
    scored_buyers = [score_buyer_profile(b, context) for b in revenue_os_output.get("buyer_profiles", [])]
    campaign_plan = generate_campaign_plan(revenue_os_output, context, request_data)

    sequence_plan = campaign_plan.get("sequence_plan", [])
    sequence_summary = []
    for seq in sequence_plan:
        for step in seq.get("steps", []):
            sequence_summary.append({
                "day": step.get("day"),
                "action": step.get("action"),
                "channel": step.get("channel"),
            })

    gtm_layer = {
        "gtm_signals": gtm_signals,
        "icp_scores": {
            "average_score": round(sum(b.get("total_score", 0) for b in scored_buyers) / len(scored_buyers), 1) if scored_buyers else 0,
            "tier_1_count": len([b for b in scored_buyers if b["tier"] == "Tier 1"]),
            "tier_2_count": len([b for b in scored_buyers if b["tier"] == "Tier 2"]),
            "tier_3_count": len([b for b in scored_buyers if b["tier"] == "Tier 3"]),
            "monitor_count": len([b for b in scored_buyers if b["tier"] == "Monitor"]),
            "excluded_count": len([b for b in scored_buyers if b["tier"] == "Exclude"]),
        },
        "buyer_tiers": [{"persona_type": b["persona_type"], "segment": b["segment"], "total_score": b["total_score"], "tier": b["tier"], "best_channel": b["best_channel"], "recommended_sequence_type": b["recommended_sequence_type"]} for b in scored_buyers[:5]],
        "detected_signals": gtm_signals.get("detected_signals", []),
        "recommended_campaign": campaign_plan.get("id"),
        "campaign_summary": {
            "total_sequences": len(sequence_plan),
            "total_steps": campaign_plan.get("total_sequence_steps", 0),
            "top_tier_buyers": campaign_plan.get("top_tier_buyers", []),
            "recommended_channel": campaign_plan.get("recommended_channel", "email"),
        },
        "sequence_plan": sequence_summary,
        "gtm_next_actions": [
            f"Target Tier 1 buyers first ({campaign_plan.get('buyer_breakdown', {}).get('tier_1_count', 0)} identified)",
            f"Run {gtm_signals.get('signal_count', 0)} detected signal(s) through personalized sequences",
            f"Best channel: {gtm_signals.get('best_channel', 'mixed')}",
            "Review campaign plan for full sequence details",
            "Track lead statuses in Pipeline Composer and update scores weekly",
        ],
    }

    revenue_os_output["gtm_layer"] = gtm_layer
    return revenue_os_output
