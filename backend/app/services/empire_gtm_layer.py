"""
Empire GTM Layer — ICP scoring, signal detection, campaign generation, sequence creation, weekly updates.
Connects to Revenue OS to provide GTM intelligence for every generated revenue system.
"""

import json
import os
import uuid
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

DATA_DIR = os.path.join(os.path.dirname(os.path.dirname(__file__)), "data", "gtm")


def _load(name: str) -> dict:
    path = os.path.join(DATA_DIR, f"{name}.json")
    if not os.path.exists(path):
        return {}
    with open(path) as f:
        return json.load(f)


def _save(name: str, data: dict):
    os.makedirs(DATA_DIR, exist_ok=True)
    path = os.path.join(DATA_DIR, f"{name}.json")
    with open(path, "w") as f:
        json.dump(data, f, indent=2)


def _load_list(name: str) -> list:
    d = _load(name)
    if isinstance(d, list):
        return d
    return d.get("campaigns", []) if name == "campaigns" else d.get("scoring_outputs", []) if name == "scoring_outputs" else d.get("updates", []) if name == "weekly_updates" else []


def _save_list(name: str, items: list):
    if name == "campaigns":
        _save(name, {"description": "GTM campaigns generated by Empire Revenue OS.", "campaigns": items})
    elif name == "scoring_outputs":
        _save(name, {"description": "Buyer scoring outputs from Empire GTM Layer.", "scoring_outputs": items})
    elif name == "weekly_updates":
        _save(name, {"description": "Weekly GTM updates generated by Empire GTM Layer.", "updates": items})


